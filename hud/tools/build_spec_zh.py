#!/usr/bin/env python3
"""Build hud/spec-zh.html: the 光学规格 (optical spec) tab of hud/index.html on its own, in Chinese.

- Only the spec explanations and pictures. No 3D model, no BOM, no expert value panel.
- Item titles stay in English (the definitions are not agreed yet).
- Korean text is swapped for Chinese with tools/spec_zh.json (Korean run -> Chinese).
  A "run" is a stretch of text between quotes, tags and ${...}; see RUN below.

Run from the repo:  python3 hud/tools/build_spec_zh.py
The Korean page is never modified.
"""
import json, pathlib, re, sys

HUD = pathlib.Path(__file__).resolve().parent.parent
SRC, OUT = HUD / 'index.html', HUD / 'spec-zh.html'
ZH = json.loads((HUD / 'tools' / 'spec_zh.json').read_text(encoding='utf-8'))
src = SRC.read_text(encoding='utf-8')

def cut(s, a, b, keep_b=False):
    i = s.index(a); j = s.index(b, i + len(a))
    return s[i:j + (len(b) if keep_b else 0)]

# Values the spec pictures borrow from the 3D optics model (virtual image distance, FOV, TFT size).
# Read from the running Korean page; update them if the model changes.
MODEL = """const OPT0 = { vid: 420, v0: { y: -0.05217898740116744 } };
let RAD = 58.20834650081151, HFOV = 0.20368025469260131, VFOV = 0.07490697896214626;
const LCDR = { w: 12.00049748256162, d: 2.730479561595165 };"""

css = cut(src, '<style>', '</style>', True)
spec_markup = cut(src, '<main id="specPage" hidden>', '</main>', True).replace('<main id="specPage" hidden>', '<main id="specPage">')
hud_paint = cut(src, 'function paintHUD(g, black) {', '\nfunction drawHUD()')
spec_js = cut(src, '/* ───────────────────────── 光学 스펙 tab'.replace('光学', '광학'), '/* ───────────────────────── BOM (')

# the expert-value panel and the parts drawing are not part of this page
spec_js = re.sub(r"<details><summary>이 값을 좌우하는 부품</summary>.*?</details>", '', spec_js, count=1)
spec_js = spec_js.replace("const EXP_KEY = 'hudexp:v1';", "const EXP_KEY = 'hudexp-zh:v1';")
spec_js = spec_js.replace("toLocaleString('ko-KR'", "toLocaleString('zh-CN'")

RUN = re.compile(r"[^`'\"<>{}$\n]*[가-힣][^`'\"<>{}$\n]*")
def zh(text):
    def sub(m):
        s = m.group(); core = s.strip()
        if core not in ZH: return s
        i = s.index(core); return s[:i] + ZH[core] + s[i + len(core):]
    return RUN.sub(sub, text)
spec_js = zh(spec_js); spec_markup = zh(spec_markup)

FONT_KO = '"Apple SD Gothic Neo", "Malgun Gothic"'
FONT_ZH = '"PingFang SC", "Microsoft YaHei", "Noto Sans SC", "WenQuanYi Zen Hei"'
spec_js = spec_js.replace(FONT_KO, FONT_ZH); hud_paint = hud_paint.replace(FONT_KO, FONT_ZH)
css = css.replace("'Apple SD Gothic Neo', 'Malgun Gothic'", "'PingFang SC', 'Microsoft YaHei', 'Noto Sans SC', 'WenQuanYi Zen Hei'")

zh_css = """<style>
/* Chinese spec page: one column, no expert panel, English item titles */
:root { --hdr: 52px !important; }
body.zh header { display: flex !important; height: calc(var(--hdr) + env(safe-area-inset-top, 0px)) !important; padding: env(safe-area-inset-top, 0px) 16px 0 !important; }
body.zh header .sub { display: inline !important; }
body.zh .sp-head, body.zh .sp-side, body.zh .sp-split, body.zh #expPanel, body.zh #xDlg, body.zh .sp-title .en, body.zh .sp-item small { display: none !important; }
body.zh .sp-detail { grid-template-columns: minmax(0, 1fr) !important; }
body.zh .sp-main { max-width: 1100px; }
@media (max-width: 640px) { body.zh header .sub { display: none !important; } }
</style>"""

page = f"""<!doctype html>
<html lang="zh-CN">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<title>AR-HUD 光学规格解读</title>
{css}
{zh_css}
</head>
<body class="zh" data-tab="spec">
<header><div class="ttl"><h1>AR-HUD 光学规格解读</h1><span class="sub">每个项目的含义与示意图 · 图中数字均为示例</span></div></header>
{spec_markup}
<script type="module">
// generated by tools/build_spec_zh.py from index.html — edit the Korean page and the dictionary, then rebuild
const $ = s => document.querySelector(s);
const mobile = () => innerWidth <= 900, phone = () => innerWidth <= 640;
let curTab = 'spec';
const P = {{}}, setTab = () => {{}}, select = () => {{}}, goView = () => {{}};
{MODEL}
const HUD_W = 1200, HUD_H = 440, ASPECT = HUD_W / HUD_H;
const hudCanvas = document.createElement('canvas'), hudClear = document.createElement('canvas');
hudCanvas.width = hudClear.width = HUD_W; hudCanvas.height = hudClear.height = HUD_H;
{hud_paint}
paintHUD(hudCanvas.getContext('2d'), true); paintHUD(hudClear.getContext('2d'), false);

{spec_js}
SPECS.forEach(s => {{ s.ko = s.en; }});
SP.view = 'items'; specTab();
</script>
</body>
</html>
"""
OUT.write_text(page, encoding='utf-8')
left = sorted({m.group().strip() for m in RUN.finditer(spec_js)})
print(f'wrote {OUT.relative_to(HUD.parent)} · {len(page) // 1024} KB · Korean runs left in code (hidden parts): {len(left)}')
